  const languageKey = "openlisapro.language";
  const supported = new Set(["en", "de"]);
  let language = localStorage.getItem(languageKey) || "en";
  if (!supported.has(language)) language = "en";
  const locale = language === "de" ? "de-DE" : "en-US";

  function t(message) {
    if (language !== "de") return message;
    if (Object.prototype.hasOwnProperty.call(messages.de, message)) return messages.de[message];
    for (const [pattern, translate] of patterns) {
      if (pattern.test(message)) return message.replace(pattern, (...args) => translate(...args));
    }
    return message;
  }

  function translateTextNode(node) {
    const value = node.nodeValue;
    if (!value || !value.trim()) return;
    const translated = t(value.trim());
    if (translated !== value.trim()) node.nodeValue = value.replace(value.trim(), translated);
  }

  function translateAttributes(element) {
    if (!element || element.nodeType !== Node.ELEMENT_NODE) return;
    for (const name of ["title", "aria-label", "placeholder"]) {
      const value = element.getAttribute(name);
      if (!value) continue;
      const translated = t(value);
      if (translated !== value) element.setAttribute(name, translated);
    }
  }

  function translateTree(node) {
    if (node.nodeType === Node.TEXT_NODE) {
      translateTextNode(node);
      return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE && node !== document) return;
    if (node.nodeType === Node.ELEMENT_NODE) translateAttributes(node);
    const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) translateTextNode(walker.currentNode);
    if (node.querySelectorAll) node.querySelectorAll("[title], [aria-label], [placeholder]").forEach(translateAttributes);
  }

  document.documentElement.lang = language;
  window.i18n = { language, locale, t };
  window.t = t;

  document.addEventListener("DOMContentLoaded", () => {
    const selector = document.getElementById("languageSelect");
    if (selector) {
      selector.value = language;
      selector.addEventListener("change", () => {
        localStorage.setItem(languageKey, selector.value);
        window.location.reload();
      });
    }
    translateTree(document.body);
  });

  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === "characterData") translateTextNode(mutation.target);
      if (mutation.type === "attributes") translateAttributes(mutation.target);
      mutation.addedNodes?.forEach(translateTree);
    }
  });
  observer.observe(document.documentElement, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: ["title", "aria-label", "placeholder"],
  });
